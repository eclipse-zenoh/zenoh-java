use crate::kotlin::kotlin_ext::KotlinFile;

pub(crate) fn emit_target(package: &str) -> KotlinFile {
    KotlinFile {
        package: package.to_string(),
        class_name: "Target".into(),
        contents: render_target_source(package),
    }
}

fn render_target_source(package: &str) -> String {
    let mut out = String::new();
    out.push_str("// Auto-generated by JniExt - do not edit by hand.\n");
    if !package.is_empty() {
        out.push_str(&format!("package {}\n\n", package));
    }
    out.push_str(
        "internal enum class Target {\n\
         \x20   WINDOWS_X86_64_MSVC,\n\
         \x20   WINDOWS_AARCH64_MSVC,\n\
         \x20   LINUX_X86_64,\n\
         \x20   LINUX_AARCH64,\n\
         \x20   APPLE_AARCH64,\n\
         \x20   APPLE_X86_64;\n\
         \n\
         \x20   override fun toString(): String = when (this) {\n\
         \x20       WINDOWS_X86_64_MSVC -> \"x86_64-pc-windows-msvc\"\n\
         \x20       WINDOWS_AARCH64_MSVC -> \"aarch64-pc-windows-msvc\"\n\
         \x20       LINUX_X86_64 -> \"x86_64-unknown-linux-gnu\"\n\
         \x20       LINUX_AARCH64 -> \"aarch64-unknown-linux-gnu\"\n\
         \x20       APPLE_AARCH64 -> \"aarch64-apple-darwin\"\n\
         \x20       APPLE_X86_64 -> \"x86_64-apple-darwin\"\n\
         \x20   }\n\
         }\n",
    );
    out
}
