package io.zenoh

import io.zenoh.jni.JNINativeLibLoader

/**
 * Static singleton class to load the Zenoh native library once and only once, as well as the logger in function of the
 * log level configuration.
 *
 * The single dylib `libzenoh_flat_jni` carries every JNI entry point (autogenerated wrappers
 * over zenoh-flat plus the mechanical `outdated/` shim that re-exports the legacy zenoh-jni
 * surface). Loading happens in [JNINativeLibLoader]; this object just touches it so the
 * `init {}` block runs before any legacy `JNI*.kt` adapter does its first JNI call.
 */
internal actual object ZenohLoad {
    init {
        JNINativeLibLoader
    }
}
